#define OLED_ADDR 0x3C
static volatile uint32_t ms;
void SysTick_Handler(void) { ms++; }

static void i2c_init(void) {
    RCC->APB2ENR |= RCC_APB2ENR_IOPBEN | RCC_APB2ENR_AFIOEN;
    RCC->APB1ENR |= RCC_APB1ENR_I2C2EN;
    gpio_cfg(GPIOB, 10, GPIO_AF_OD_50MHZ);         /* SCL */
    gpio_cfg(GPIOB, 11, GPIO_AF_OD_50MHZ);          /* SDA */
    I2C2->CR2 = 8;                                 /* PCLK1 = 8 MHz */
    I2C2->CCR = 40;                                /* 8 MHz / (2 x 40) = 100 kHz */
    I2C2->TRISE = 9;
    I2C2->CR1 = I2C_CR1_PE;
}
static int i2c_start(uint8_t addr_rw) {              /* returns 1 on ACK, 0 on NACK */
    I2C2->CR1 |= I2C_CR1_START;
    while (!(I2C2->SR1 & I2C_SR1_SB));
    I2C2->DR = addr_rw;
    for (;;) {
        uint32_t s = I2C2->SR1;
        if (s & I2C_SR1_ADDR) { (void)I2C2->SR2; return 1; }
        if (s & I2C_SR1_AF) { I2C2->SR1 &= ~I2C_SR1_AF; I2C2->CR1 |= I2C_CR1_STOP; while (I2C2->CR1 & I2C_CR1_STOP); return 0; }
    }
}
static void i2c_put(uint8_t b) { while (!(I2C2->SR1 & I2C_SR1_TXE)); I2C2->DR = b; }
static void i2c_stop(void) { while (!(I2C2->SR1 & I2C_SR1_BTF)); I2C2->CR1 |= I2C_CR1_STOP; while (I2C2->CR1 & I2C_CR1_STOP); }

static void oled_cmds(const uint8_t *c, int n) {
    if (!i2c_start(OLED_ADDR << 1)) return;
    i2c_put(0x00);                                 /* control byte: command stream */
    while (n--) i2c_put(*c++);
    i2c_stop();
}
static void oled_data(const uint8_t *d, int n) {
    if (!i2c_start(OLED_ADDR << 1)) return;
    i2c_put(0x40);                                 /* control byte: data stream */
    while (n--) i2c_put(*d++);
    i2c_stop();
}
static void oled_init(void) {
    static const uint8_t init[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0x8D, 0x14,   /* off, clock, mux 64, offset, start line, charge pump on */
        0x20, 0x02, 0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF };
    oled_cmds(init, sizeof init);
}
static void oled_pos(int page, int col) {
    uint8_t c[3] = { (uint8_t)(0xB0 | page), (uint8_t)(col & 15), (uint8_t)(0x10 | (col >> 4)) };
    oled_cmds(c, 3);
}
static void oled_clear(void) {
    static const uint8_t zero[128];
    for (int p = 0; p < 8; p++) { oled_pos(p, 0); oled_data(zero, 128); }
}
static void oled_text(int page, int col, const char *s) {
    uint8_t buf[128]; int n = 0;
    for (; *s && n + 6 <= 128; s++) {
        const uint8_t *g = font5x7[(*s - 32) % 95];
        for (int i = 0; i < 5; i++) buf[n++] = g[i];
        buf[n++] = 0;
    }
    oled_pos(page, col); oled_data(buf, n);
}
static void oled_rule(int page) { uint8_t b[128]; for (int i = 0; i < 128; i++) b[i] = 0x08; oled_pos(page, 0); oled_data(b, 128); }

int main(void) {
    i2c_init();
    SysTick->LOAD = 8000 - 1; SysTick->CTRL = 7;   /* 1 ms tick */
    oled_init();
    oled_clear();
    oled_text(0, 0, "Hello, PinForge!");
    oled_rule(1);
    oled_text(2, 0, "SSD1306 128x64");
    oled_text(4, 0, "I2C2 100 kHz  0x3C");
    uint32_t shown = 99999;
    for (;;) {
        uint32_t s = ms / 1000;
        if (s != shown) {
            shown = s;
            char b[22] = "Uptime: "; int n = 8; char d[11]; int k = 0; uint32_t v = s;
            do { d[k++] = (char)('0' + v % 10); v /= 10; } while (v);
            while (k) b[n++] = d[--k];
            b[n++] = ' '; b[n++] = 's'; b[n++] = ' '; b[n++] = ' '; b[n] = 0;
            oled_text(6, 0, b);
        }
    }
}
