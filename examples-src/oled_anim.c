#define OLED_ADDR 0x3C
static volatile uint32_t ms;
void SysTick_Handler(void) { ms++; }
static uint8_t fb[1024];

static void i2c_init(void) {
    RCC->APB2ENR |= RCC_APB2ENR_IOPBEN | RCC_APB2ENR_AFIOEN;
    RCC->APB1ENR |= RCC_APB1ENR_I2C2EN;
    gpio_cfg(GPIOB, 10, GPIO_AF_OD_50MHZ);
    gpio_cfg(GPIOB, 11, GPIO_AF_OD_50MHZ);
    I2C2->CR2 = 8;
    I2C2->CCR = I2C_CCR_FS | 7;                    /* fast mode: 3 x 7 / 8 MHz = 2.6 us period */
    I2C2->TRISE = 3;
    I2C2->CR1 = I2C_CR1_PE;
}
static int i2c_start(uint8_t addr_rw) {              /* returns 1 on ACK, 0 on NACK */
    I2C2->CR1 |= I2C_CR1_START;
    while (!(I2C2->SR1 & I2C_SR1_SB));
    I2C2->DR = addr_rw;
    for (;;) {
        uint32_t s = I2C2->SR1;
        if (s & I2C_SR1_ADDR) { (void)I2C2->SR2; return 1; }
        if (s & I2C_SR1_AF) { I2C2->SR1 &= ~I2C_SR1_AF; I2C2->CR1 |= I2C_CR1_STOP; while (I2C2->CR1 & I2C_CR1_STOP); return 0; }
    }
}
static void i2c_put(uint8_t b) { while (!(I2C2->SR1 & I2C_SR1_TXE)); I2C2->DR = b; }
static void i2c_stop(void) { while (!(I2C2->SR1 & I2C_SR1_BTF)); I2C2->CR1 |= I2C_CR1_STOP; while (I2C2->CR1 & I2C_CR1_STOP); }

static void oled_cmds(const uint8_t *c, int n) {
    if (!i2c_start(OLED_ADDR << 1)) return;
    i2c_put(0x00); while (n--) i2c_put(*c++); i2c_stop();
}
static void oled_flush(void) {
    static const uint8_t win[] = { 0x21, 0, 127, 0x22, 0, 7 };   /* column 0..127, page 0..7 */
    oled_cmds(win, sizeof win);
    if (!i2c_start(OLED_ADDR << 1)) return;
    i2c_put(0x40);
    for (int i = 0; i < 1024; i++) i2c_put(fb[i]);
    i2c_stop();
}
static void px(int x, int y) { if ((unsigned)x < 128 && (unsigned)y < 64) fb[(y >> 3) * 128 + x] |= (uint8_t)(1u << (y & 7)); }
static void line(int x0, int y0, int x1, int y1) {
    int dx = x1 > x0 ? x1 - x0 : x0 - x1, sx = x0 < x1 ? 1 : -1, dy = y1 > y0 ? y0 - y1 : y1 - y0, sy = y0 < y1 ? 1 : -1, e = dx + dy;
    for (;;) { px(x0, y0); if (x0 == x1 && y0 == y1) break; int e2 = 2 * e; if (e2 >= dy) { e += dy; x0 += sx; } if (e2 <= dx) { e += dx; y0 += sy; } }
}
static void disc(int cx, int cy, int r) { for (int y = -r; y <= r; y++) for (int x = -r; x <= r; x++) if (x * x + y * y <= r * r + r / 2) px(cx + x, cy + y); }
static void text(int x, int y, const char *s) {
    for (; *s; s++, x += 6) { const uint8_t *g = font5x7[(*s - 32) % 95]; for (int c = 0; c < 5; c++) for (int r = 0; r < 8; r++) if ((g[c] >> r) & 1) px(x + c, y + r); }
}
static void num(int x, int y, uint32_t v) { char d[11]; int k = 0; do { d[k++] = (char)('0' + v % 10); v /= 10; } while (v); char b[12]; int n = 0; while (k) b[n++] = d[--k]; b[n] = 0; text(x, y, b); }

int main(void) {
    static const uint8_t init[] = { 0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0x8D, 0x14, 0x20, 0x00, 0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF };
    i2c_init();
    SysTick->LOAD = 8000 - 1; SysTick->CTRL = 7;
    oled_cmds(init, sizeof init);
    int bx = 20, by = 30, vx = 2, vy = 1; static uint8_t hist[128]; uint32_t frames = 0, fps = 0, t0 = 0, next = 0, tick = 0;
    for (;;) {
        while (ms < next) { }
        next = ms + 40;                                             /* about 25 frames per second */
        for (int i = 0; i < 1024; i++) fb[i] = 0;
        bx += vx; by += vy; if (bx < 4 || bx > 123) vx = -vx; if (by < 18 || by > 43) vy = -vy;
        for (int x = 0; x < 128; x++) { px(x, 63); if ((x & 7) == 0) px(x, 62); }
        line(0, 16, 127, 16);
        text(0, 4, "PinForge OLED"); num(88, 4, fps); text(106, 4, "fps");
        disc(bx, by, 4);
        hist[tick & 127] = (uint8_t)((by - 18) * 12 / 25);              /* history of the ball's height */
        tick++;
        for (int x = 1; x < 128; x++) line(x - 1, 60 - hist[(tick + x - 1) & 127], x, 60 - hist[(tick + x) & 127]);
        oled_flush(); frames++;
        if (ms - t0 >= 1000) { fps = frames * 1000 / (ms - t0); frames = 0; t0 = ms; }
    }
}
